#!/usr/bin/env node
// Reads icons/*.svg (the hand-drawn sources) and writes
//   icons/sprite.svg          one <symbol id="i-NAME"> per icon
//   src/icons.generated.ts    the same paths as strings, for @loch/design/icons
// Both outputs are committed; this runs again on every build.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const pkg = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(pkg, "icons");
const names = readdirSync(dir)
  .filter((f) => f.endsWith(".svg") && f !== "sprite.svg")
  .map((f) => f.slice(0, -4))
  .sort();

const ROOT = /^<svg xmlns="http:\/\/www\.w3\.org\/2000\/svg" viewBox="0 0 20 20" width="20" height="20" fill="none" stroke="currentColor" stroke-width="1\.5" stroke-linecap="round" stroke-linejoin="round">\n([\s\S]*)\n<\/svg>\n$/;

const bodies = {};
for (const name of names) {
  const text = readFileSync(join(dir, `${name}.svg`), "utf8");
  const match = ROOT.exec(text);
  if (!match) {
    console.error(`icons/${name}.svg: the root element must be exactly the standard one (20px grid, stroke 1.5, round, currentColor)`);
    process.exit(1);
  }
  const body = match[1].split("\n").map((l) => l.trim()).join("");
  if (/fill="(?!none)|stroke="(?!currentColor)|style=|<script|href=/.test(body)) {
    console.error(`icons/${name}.svg: only stroked shapes in currentColor are allowed`);
    process.exit(1);
  }
  bodies[name] = body;
}

const attrs = 'fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round"';
const sprite =
  // No style attribute: a Content-Security-Policy without 'unsafe-inline' refuses one. The sprite
  // takes no room by its width and height of 0, and `.sprite` (components.css) takes it out of the flow.
  `<svg xmlns="http://www.w3.org/2000/svg" class="sprite" width="0" height="0" aria-hidden="true" focusable="false">\n` +
  `  <!-- @loch/design icons. Generated by scripts/build-icons.mjs from icons/*.svg. Do not edit. -->\n` +
  names.map((n) => `  <symbol id="i-${n}" viewBox="0 0 20 20" ${attrs}>${bodies[n]}</symbol>`).join("\n") +
  `\n</svg>\n`;
writeFileSync(join(dir, "sprite.svg"), sprite);

const ts =
  `// Generated by scripts/build-icons.mjs from icons/*.svg. Do not edit.\n` +
  `export const ICON_BODIES = {\n` +
  names.map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(bodies[n])},`).join("\n") +
  `\n} as const;\n\n` +
  `export const SPRITE = ${JSON.stringify(sprite)};\n`;
writeFileSync(join(pkg, "src", "icons.generated.ts"), ts);
console.log(`icons: ${names.length} icons -> icons/sprite.svg, src/icons.generated.ts`);
